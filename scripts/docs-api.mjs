import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { pathToFileURL } from "node:url";

export async function registeredRoutes() {
  const routes = [];
  for (const source of ["packages/server/app.ts", "packages/server/studio-routes.ts"]) {
    const code = await readFile(source, "utf8");
    // These two registration modules deliberately use only literal app.method paths.
    if (
      /\bapp\.(?:route|register)\s*\(/.test(code.replace(/await app\.register\([^;]+;/gs, "")) ||
      /\bapp\s*\[/.test(code)
    )
      throw new Error("Review the API extractor for a new registration pattern.");
    const calls = [...code.matchAll(/\bapp\.(get|post|put|delete|patch|options|head)\s*\(/g)];
    for (const call of calls) {
      const path = /^\s*"([^"\n]+)"/.exec(code.slice(call.index + call[0].length));
      if (!path) throw new Error("Document dynamic routes explicitly before changing the extractor.");
      routes.push({ key: `${call[1].toUpperCase()} ${path[1]}`, source });
    }
  }
  return routes.sort((a, b) => a.key.localeCompare(b.key));
}

export function assertCoverage(routes, contracts) {
  const actual = routes.map((r) => r.key).sort(),
    documented = Object.keys(contracts).sort();
  if (new Set(actual).size !== actual.length || JSON.stringify(actual) !== JSON.stringify(documented))
    throw new Error("API contract coverage differs from registered routes. Review docs/api-contracts.json.");
  for (const [key, contract] of Object.entries(contracts))
    for (const field of ["access", "request", "response", "errors", "contract"])
      if (typeof contract[field] !== "string" || !contract[field].trim())
        throw new Error(`Missing ${field}: ${key}`);
}

export async function checkApiDocs(write = false) {
  const routes = await registeredRoutes();
  const manifest = JSON.parse(await readFile("docs/api-contracts.json", "utf8"));
  assertCoverage(routes, manifest.routes);
  // Explicit reviewed fingerprints catch DTO/service drift as well as renamed routes.
  // --write refreshes generated output only; it does NOT approve new fingerprints.
  for (const [source, expected] of Object.entries(manifest.reviewedSources)) {
    const digest = createHash("sha256")
      .update((await readFile(source, "utf8")).replaceAll("\r\n", "\n"))
      .digest("hex");
    if (digest !== expected)
      throw new Error(
        `Contract source changed: ${source}. Reconcile its documentation, then update the reviewed fingerprint.`,
      );
  }
  const sections = routes.map(({ key, source }) => {
    const c = manifest.routes[key];
    return `## ${key}\n\n- **Access:** ${c.access}\n- **Request:** ${c.request}\n- **Response:** ${c.response}\n- **Errors:** ${c.errors}\n- **Contract:** ${c.contract}\n- **Registration:** \`${source}\`\n`;
  });
  // Text is maintained in JSON to avoid a second handwritten endpoint list.
  const output =
    `# API route contracts\n\nGenerated by \`node scripts/docs-api.mjs --write\` from reviewed \`docs/api-contracts.json\`. Do not edit this page by hand.\n\n${routes.length} explicit HTTP routes are covered. See [API conventions](API.md) for authentication, DTO definitions, error handling, quotas and safe examples. Schema/service fingerprints require an explicit documentation review after changes. This is structural contract coverage, not a claim of exhaustive runtime or formal OpenAPI validation.\n\n` +
    sections.join("\n");
  if (write) await writeFile("docs/API-REFERENCE.md", output, "utf8");
  else if ((await readFile("docs/API-REFERENCE.md", "utf8")).replaceAll("\r\n", "\n") !== output)
    throw new Error("Generated API reference is stale. Run node scripts/docs-api.mjs --write.");
  return routes.length;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  console.log(`API route/contract coverage: ${await checkApiDocs(process.argv.includes("--write"))} routes.`);
